// Rebuild the sharing image and its exact HTML reference:
// node scripts/build-og.mjs --sharp-module <path-to-sharp>
// Requires Python with fontTools/Brotli and sharp (local or --sharp-module).
// Text is outlined from the repository's Lato fonts so rendering is font-independent.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);
const moduleFlag = process.argv.indexOf('--sharp-module');
const sharp = require(moduleFlag >= 0 ? process.argv[moduleFlag + 1] : 'sharp');
const runs = [
  { text: 'Dmytro Zatserkivnyi', x: 72, y: 90, size: 25, weight: 700, fill: '#19212F' },
  { text: 'Web developer / freelancer', x: 72, y: 121, size: 18, weight: 400, fill: '#586477' },
  { text: 'Strony i sklepy.', x: 72, y: 245, size: 76, weight: 900, fill: '#19212F', tracking: -1.8 },
  { text: 'Bezpośrednio', x: 72, y: 330, size: 76, weight: 900, fill: '#19212F', tracking: -1.8 },
  { text: 'ze mną.', x: 72, y: 415, size: 76, weight: 900, fill: '#19212F', tracking: -1.8 },
  { text: 'WordPress, sklepy i aplikacje webowe', x: 75, y: 473, size: 23, weight: 400, fill: '#586477' },
  { text: 'dmytro-dev.pl', x: 75, y: 567, size: 23, weight: 700, fill: '#254BE8' },
  { text: 'dz.', x: 891, y: 227, size: 42, weight: 900, fill: '#254BE8', tracking: -1 },
];
const python = String.raw`
import json, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
data = json.loads(sys.stdin.buffer.read().decode('utf-8'))
fonts = {}
for weight in (400,700,900):
    fonts[weight] = [TTFont(Path(data['root'])/'assets'/'fonts'/('lato-%s-%s.woff2'%(weight,subset))) for subset in ('latin','latin-ext')]
out = []
for run in data['runs']:
    x = run['x']
    for char in run['text']:
        font = next((f for f in fonts[run['weight']] if ord(char) in f.getBestCmap()), None)
        if font is None: raise ValueError('Missing character: '+char)
        glyph = font.getBestCmap()[ord(char)]
        scale = run['size']/font['head'].unitsPerEm
        pen = SVGPathPen(font.getGlyphSet())
        font.getGlyphSet()[glyph].draw(pen)
        outline = pen.getCommands()
        if outline:
            out.append('<path fill="%s" transform="translate(%s %s) scale(%s %s)" d="%s"/>'%(run['fill'],x,run['y'],scale,-scale,outline))
        x += font['hmtx'][glyph][0]*scale + run.get('tracking',0)
print(''.join(out))
`;
const result = spawnSync(process.env.PYTHON || 'python', ['-c', python], {
  input: JSON.stringify({ root, runs }), encoding: 'utf8', maxBuffer: 8 * 1024 * 1024,
});
if (result.error || result.status !== 0) throw result.error || new Error(result.stderr);
